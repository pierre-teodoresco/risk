const COLOUR_NAMES: Record<Lang, Record<string, string>> = { fr: fr.colors, en: en.colors };

/** Journal lines worth a toast; plays and draws are already visible on the table. */
export function eventText(key: string, a: string[], lang: Lang) {
  const t: Record<string, [string, string]> = {
    joined: [`${a[0]} rejoint la table.`, `${a[0]} joins the table.`],
    started: [`${a[0]} distribue.`, `${a[0]} deals.`],
    skipped: [`${a[0]} passe son tour.`, `${a[0]} is skipped.`],
    reversed: ["Le sens du jeu s’inverse.", "Direction reversed."],
    chose: [`${a[0]} choisit le ${COLOUR_NAMES.fr[a[1]] ?? a[1]}.`, `${a[0]} chooses ${COLOUR_NAMES.en[a[1]] ?? a[1]}.`],
    called: [`${a[0]} : « Dernière carte ! »`, `${a[0]}: “Last card!”`],
    caught: [`${a[0]} crie « Dernière carte ! » : ${a[1]} pioche 2.`, `${a[0]} shouts “Last card!”: ${a[1]} draws 2.`],
    // Events saved before lots of +4 carry no amount: a single +4 was at stake.
    challengeWon: [`${a[0]} conteste avec succès : ${a[1]} pioche ${a[2] ?? 4}.`, `${a[0]} wins the challenge: ${a[1]} draws ${a[2] ?? 4}.`],
    challengeLost: [`${a[0]} conteste à tort et pioche ${a[2] ?? 6}.`, `${a[0]} loses the challenge and draws ${a[2] ?? 6}.`],
    combo: [`${a[0]} pose ${a[1]} cartes d’un coup !`, `${a[0]} plays ${a[1]} cards at once!`],
    swapped: [`${a[0]} échange sa main avec ${a[1]}.`, `${a[0]} swaps hands with ${a[1]}.`],
    rotated: ["Toutes les mains tournent !", "Every hand moves along!"],
    timeout: [`Temps écoulé pour ${a[0]}.`, `Time is up for ${a[0]}.`],
    left: [`${a[0]} quitte la table.`, `${a[0]} leaves the table.`],
    resigned: [`${a[0]} abandonne la manche.`, `${a[0]} gives up the round.`],
    host: [`${a[0]} devient l’hôte.`, `${a[0]} becomes host.`],
    paused: ["Partie en pause.", "Game paused."],
    resumed: ["La partie reprend.", "The game resumes."],
  };
  return t[key]?.[lang === "fr" ? 0 : 1] ?? null;
}

export function cardLabel(card: Card, tx: PiocheTexts) {
  const color = card.color ? tx.colors[card.color] : "";
  const what = card.kind === "number" ? String(card.value) : tx.kinds[card.kind];
  return color ? `${what} ${color}` : what;
}
