    swapped: [`${a[0]} échange sa main avec ${a[1]}.`, `${a[0]} swaps hands with ${a[1]}.`],
    rotated: ["Toutes les mains tournent !", "Every hand moves along!"],
    timeout: [`Temps écoulé pour ${a[0]}.`, `Time is up for ${a[0]}.`],
