export function cardLabel(card: Card, tx: PiocheTexts) {
  const color = card.color ? tx.colors[card.color] : "";
  const what = card.kind === "number" ? String(card.value) : tx.kinds[card.kind];
  return color ? `${what} ${color}` : what;
}
