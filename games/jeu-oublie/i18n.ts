export function errorText(code: string, lang: Lang) {
  const errors: Record<string, [string, string]> = {
    playerCount: ["Il faut 2 à 4 joueurs.", "You need 2 to 4 players."],
    invalidFaction: ["Cette faction n'existe pas (encore).", "That faction does not exist (yet)."],
    roomFull: ["La partie est complète : 4 joueurs maximum.", "The game is full: 4 players at most."],
  };
  return errors[code]?.[lang === "fr" ? 0 : 1] ?? sharedError(code, lang);
}
