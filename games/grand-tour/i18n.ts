/** Display name of square `i`. */
export function squareName(i: number, lang: Lang) {
  const s = BOARD[i], t = gtTexts(lang).square;
  if (!s) return "";
  if (s.kind === "city" || s.kind === "airport" || s.kind === "utility") return lang === "en" ? AIRPORTS_EN[s.name] ?? s.name : s.name;
  if (s.kind === "tax") return t[s.label];
  return t[s.kind];
}
